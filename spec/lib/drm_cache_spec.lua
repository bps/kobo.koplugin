require("spec.helper")

describe("DRM cache preservation", function()
    it("does not truncate an existing decrypted book when ensuring its path", function()
        local cache = require("src/lib/drm/cache_manager")
        local path = os.tmpname()
        local file = assert(io.open(path, "w"))
        file:write("previously decrypted book")
        file:close()
        finally(function() os.remove(path) end)
        local directory, name = path:match("^(.*)/([^/]+)$")
        local ensure_dir = stub(cache, "ensureCacheDir", function() return true end)
        finally(function() ensure_dir:revert() end)

        assert.are.equal(path, cache:ensureCachePath(name, directory))
        file = assert(io.open(path, "r"))
        local content = file:read("*a")
        file:close()
        assert.are.equal("previously decrypted book", content)
    end)
end)
